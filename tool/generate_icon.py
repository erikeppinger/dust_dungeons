"""Generates the launcher icon and splash picture from the pixel shield.

The shield is assets/art/icons/app_shield.png (16x16, see docs/ART_GUIDE.md).
Writes the legacy PNG icons on parchment, the adaptive icon foreground, the
vector used by the splash screens and the Windows icon. Run from the project
root:

    python tool/generate_icon.py
"""

from pathlib import Path

from PIL import Image

RES = Path("android/app/src/main/res")
WINDOWS_ICON = Path("windows/runner/resources/app_icon.ico")
SHIELD = Path("assets/art/icons/app_shield.png")
PARCHMENT = (0xF3, 0xE5, 0xC3, 255)
FRAME = (0x3A, 0x24, 0x14, 255)


def shield():
    img = Image.open(SHIELD).convert("RGBA")
    assert img.size == (16, 16), f"{SHIELD} must be 16x16"
    return img


def legacy_png(size):
    """Parchment tile with an ink frame and the shield, sharp pixels."""
    img = Image.new("RGBA", (24, 24), PARCHMENT)
    for i in range(1, 23):
        for x, y in ((i, 0), (i, 23), (0, i), (23, i)):
            img.putpixel((x, y), FRAME)
    img.alpha_composite(shield(), (4, 4))
    return img.resize((size, size), Image.NEAREST)


def windows_icon():
    """The bare shield in the sizes Windows asks for, sharp pixels.

    No parchment tile, unlike Android: the shield fills its 16-pixel grid,
    so every size is a whole multiple, down to the title bar's 16 pixels.
    """
    tile = shield()
    sizes = [256, 128, 64, 48, 32, 16]
    images = [tile.resize((s, s), Image.NEAREST) for s in sizes]
    images[0].save(
        WINDOWS_ICON,
        format="ICO",
        sizes=[(s, s) for s in sizes],
        append_images=images[1:],
    )


def vector(cell, offset, viewport):
    """The shield as an Android vector drawable, one path per color."""
    img = shield()
    by_color = {}
    for y in range(16):
        for x in range(16):
            r, g, b, a = img.getpixel((x, y))
            if a:
                by_color.setdefault("#%02X%02X%02X" % (r, g, b), []).append((x, y))
    paths = [
        f'    <path android:fillColor="{color}" android:pathData="'
        + "".join(
            f"M{offset + x * cell},{offset + y * cell}h{cell}v{cell}h-{cell}z"
            for x, y in pixels
        )
        + '" />'
        for color, pixels in by_color.items()
    ]
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/generate_icon.py -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{viewport}dp"\n'
        f'    android:height="{viewport}dp"\n'
        f'    android:viewportWidth="{viewport}"\n'
        f'    android:viewportHeight="{viewport}">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


def main():
    for density, size in {
        "mdpi": 48,
        "hdpi": 72,
        "xhdpi": 96,
        "xxhdpi": 144,
        "xxxhdpi": 192,
    }.items():
        legacy_png(size).save(RES / f"mipmap-{density}" / "ic_launcher.png")
    # Adaptive icons are 108 units with a 66-unit safe circle: the shield
    # takes 48 units in the middle.
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(
        vector(3, 30, 108), encoding="utf-8"
    )
    windows_icon()


if __name__ == "__main__":
    main()
