"""Generates the pixel-art launcher icon and splash picture (our own, GPL).

A green shield with a gold check on parchment, drawn on a 16x16 grid.
Writes the legacy PNG icons, the adaptive icon (vector foreground) and the
vector used by the splash screens. Run from the project root:

    python tool/generate_icon.py
"""

from pathlib import Path

from PIL import Image

RES = Path("android/app/src/main/res")

COLORS = {
    "k": "#3A2414",  # outline
    "g": "#3E8E35",  # shield
    "G": "#2B6E24",  # shield shade
    "w": "#8FD27A",  # shine
    "y": "#F2B630",  # check
    "Y": "#B07A10",  # check shade
}
PARCHMENT = "#F3E5C3"

SHIELD = [
    "................",
    ".kkkkkkkkkkkkkk.",
    ".kwwggggggggGGk.",
    ".kwgggggggggyGk.",
    ".kwggggggggyYGk.",
    ".kwgggggggyYgGk.",
    ".kwgyggggyYggGk.",
    ".kwgYyggyYgggGk.",
    ".kwggYyyYggggGk.",
    "..kwggYYggggGk..",
    "..kwggggggggGk..",
    "...kwggggggGk...",
    "....kwggggGk....",
    ".....kwggGk.....",
    "......kGGk......",
    ".......kk.......",
]


def hex_rgba(h):
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4)) + (255,)


def legacy_png(size):
    """Parchment tile with an ink frame and the shield, sharp pixels."""
    img = Image.new("RGBA", (24, 24), hex_rgba(PARCHMENT))
    frame = hex_rgba(COLORS["k"])
    for i in range(1, 23):
        for x, y in ((i, 0), (i, 23), (0, i), (23, i)):
            img.putpixel((x, y), frame)
    for y, row in enumerate(SHIELD):
        for x, ch in enumerate(row):
            if ch != ".":
                img.putpixel((x + 4, y + 4), hex_rgba(COLORS[ch]))
    return img.resize((size, size), Image.NEAREST)


def vector(cell, offset, viewport):
    """The shield as an Android vector drawable, one path per color."""
    paths = []
    for ch, color in COLORS.items():
        data = "".join(
            f"M{offset + x * cell},{offset + y * cell}h{cell}v{cell}h-{cell}z"
            for y, row in enumerate(SHIELD)
            for x, c in enumerate(row)
            if c == ch
        )
        paths.append(
            f'    <path android:fillColor="{color}" android:pathData="{data}" />'
        )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/generate_icon.py -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{viewport}dp"\n'
        f'    android:height="{viewport}dp"\n'
        f'    android:viewportWidth="{viewport}"\n'
        f'    android:viewportHeight="{viewport}">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


def main():
    for density, size in {
        "mdpi": 48,
        "hdpi": 72,
        "xhdpi": 96,
        "xxhdpi": 144,
        "xxxhdpi": 192,
    }.items():
        legacy_png(size).save(RES / f"mipmap-{density}" / "ic_launcher.png")
    # Adaptive icons are 108 units with a 66-unit safe circle: the shield
    # takes 48 units in the middle.
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(
        vector(3, 30, 108), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
